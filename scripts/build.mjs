import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const assembler=process.argv[2]||process.env.SJASMPLUS||'sjasmplus';
const result=spawnSync(assembler,['--raw=../xain-msx2.rom','--sym=../symbols.txt','game.asm'],{cwd:path.join(root,'src'),stdio:'inherit'});
if(result.error)throw result.error;
if(result.status!==0)process.exit(result.status||1);
const rom=fs.readFileSync(path.join(root,'xain-msx2.rom'));
if(rom.length!==1048576||rom.toString('ascii',0,2)!=='AB')throw new Error('ROM ASCII16 non valida');
const htmlPath=path.join(root,'index.html');
let html=fs.readFileSync(htmlPath,'utf8');
if(!/base64,[A-Za-z0-9+/=]+/.test(html))throw new Error('ROM incorporata non trovata');
html=html.replace(/(?<=base64,)[A-Za-z0-9+/=]+/g,rom.toString('base64'));
fs.writeFileSync(htmlPath,html);
console.log('ROM MSX2 da 1 MiB e copia WebMSX aggiornate.');
